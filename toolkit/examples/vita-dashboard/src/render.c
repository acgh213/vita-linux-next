#define FONT_FIRST 0x20
#define FONT_LAST  0x7E
#define GLYPH_W 8
#define GLYPH_H 8

int render_init(struct renderer *r, unsigned int width, unsigned int height,
                unsigned int bpp, unsigned int stride)
{
    size_t i;

    r->shadow = NULL;
    r->frame_bytes = 0;
    r->width = 0;
    r->height = 0;
    r->stride = 0;
    r->bytes_per_pixel = 0;
    r->clipped_writes = 0;

    if (width == 0 || height == 0 || bpp == 0 || (bpp % 8u) != 0)
        return -1;
    if (stride == 0)
        stride = width * (bpp / 8u);
    if (stride < width * (bpp / 8u))
        return -1;

    r->frame_bytes = (size_t)stride * height;
    if (r->frame_bytes == 0 || r->frame_bytes > (64u * 1024u * 1024u))
        return -1;

    r->shadow = malloc(r->frame_bytes);
    if (r->shadow == NULL) {
        r->frame_bytes = 0;
        return -1;
    }
    for (i = 0; i < r->frame_bytes; i++)
        r->shadow[i] = 0;

    r->width = width;
    r->height = height;
    r->stride = stride;
    r->bytes_per_pixel = bpp / 8u;
    return 0;
}

void render_free(struct renderer *r)
{
    if (r->shadow != NULL) {
        free(r->shadow);
        r->shadow = NULL;
    }
    r->frame_bytes = 0;
}

/* The single choke point: every pixel write in this file goes through here. */
static void put_pixel(struct renderer *r, int x, int y, unsigned int rgba)
{
    unsigned char *pixel;
    size_t offset;

    if (x < 0 || y < 0)
        return;
    if ((unsigned int)x >= r->width || (unsigned int)y >= r->height)
        return;

    offset = ((size_t)y * r->stride) + ((size_t)x * r->bytes_per_pixel);
    if (offset + r->bytes_per_pixel > r->frame_bytes)
        return;

    pixel = r->shadow + offset;
    /* PSTV memory order is RGBA (a8b8g8r8 in DRM naming). */
    pixel[0] = (unsigned char)((rgba >> 24) & 0xFFu);
    pixel[1] = (unsigned char)((rgba >> 16) & 0xFFu);
    pixel[2] = (unsigned char)((rgba >> 8) & 0xFFu);
    if (r->bytes_per_pixel >= 4)
        pixel[3] = (unsigned char)(rgba & 0xFFu);
}

void render_rect(struct renderer *r, int x, int y, int w, int h,
                 unsigned int rgba)
{
    int row, col;

    if (w <= 0 || h <= 0)
        return;
    if (x < 0 || y < 0 || (long)x + w > (long)r->width
            || (long)y + h > (long)r->height)
        r->clipped_writes++;

    for (row = y; row < y + h; row++)
        for (col = x; col < x + w; col++)
            put_pixel(r, col, row, rgba);
}

void render_clear(struct renderer *r, unsigned int rgba)
{
    render_rect(r, 0, 0, (int)r->width, (int)r->height, rgba);
}

int render_text(struct renderer *r, int x, int y, const char *text,
                unsigned int scale, unsigned int rgba)
{
    int pen = x;

    if (text == NULL)
        return 0;
    if (scale == 0)
        scale = 1;

    while (*text != '\0') {
        unsigned char ch = (unsigned char)*text;
        const unsigned char *glyph;
        unsigned int gy, gx;

        if (ch < FONT_FIRST || ch > FONT_LAST)
            ch = '?';
        glyph = font8x8[ch - FONT_FIRST];

        for (gy = 0; gy < GLYPH_H; gy++) {
            unsigned char bits = glyph[gy];

            for (gx = 0; gx < GLYPH_W; gx++) {
                /* MSB-first, matching the loader's msx_font convention. */
                if ((bits & (0x80u >> gx)) == 0)
                    continue;
                render_rect(r, pen + (int)(gx * scale),
                            y + (int)(gy * scale),
                            (int)scale, (int)scale, rgba);
            }
        }

        pen += (int)((GLYPH_W + 1) * scale);
        text++;
    }

    return pen - x;
}

void render_row(struct renderer *r, int x, int y, const char *label,
                const char *value, unsigned int scale,
                unsigned int label_rgba, unsigned int value_rgba)
{
    if (scale == 0)
        scale = 1;
    render_text(r, x, y, label, scale, label_rgba);
    /* Fixed value column keeps rows aligned without measuring the label. */
    render_text(r, x + (int)(18u * (GLYPH_W + 1) * scale), y, value, scale,
                value_rgba);
}
